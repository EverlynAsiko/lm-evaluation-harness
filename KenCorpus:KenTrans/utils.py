def code_to_language(code: str) -> str:
    """
    Converts a language code to the full language name

    code: The code representing a language

    name: str
            - The full name of the language
    
    """
    code_map = {
        "swa": "Swahili",
        "dho": "Dholuo",
        "lch": "Lumarachi",
        "llg": "Lulogooli",
        "lbk": "Lubukusu"
    }
    # Returns Unknown in case of an error
    return code_map.get(code, f"Unknown ({code})")


def generate_yamls(output_dir: str, overwrite: bool, src: str, tgt: str) -> None:
    """
    Generates a yaml file for conversion of a defined language pair.

    output_dir: The directory to output the files to (configs).
    overwrite: Whether to overwrite files if they already exist (Set to true).
    src: Source language code.
    tgt: Target language code.
    """
    # Skip same language pairs
    if src == tgt:
        return

    # Create te language pairs and name the files with the language pair
    lang_pair = f"{src}-{tgt}"
    file_name = f"KenTrans_{lang_pair}.yaml"
    file_path = os.path.join(output_dir, file_name)

    # Define the name of the file as the task name
    task_name = os.path.splitext(file_name)[0]

    # Use 'w' (write/overwrite) or 'x' (exclusive create) mode
    mode = "w" if overwrite else "x"

    try:
        source_name, target_name = code_to_language(src), code_to_language(tgt) 

        config = {
            # Generation of the conversion YAML commands
            "task": task_name,
            "dataset_path": DATASET_NAME,
            "dataset_name": src,
            "test_split": "train",
            "output_type": "generate_until",
            "doc_to_text": (
                f'Translate the following source phrase ({source_name}) to ({target_name}):\n{{translation["{src}"]}}'
            ),
            "doc_to_target": f' {{translation["{tgt}"]}}',

            "metric_list": {
                "metric": "bleu",
                "higher_is_better": True
            }
        }   

            # "source_field": f"translation.{src}",
            # "target_field": f"translation.{tgt}",
            
            
            # "doc_to_target": f' {{translation["{tgt}"]}}',
            # # Creating a prompt that generated target phrases from the source
            # "doc_to_text": (
            #     f'Translate the following source phrase ({source_name}) to ({target_name}):\n{{translation["{src}"]}}'
            # ),
            # # ------------------------------------
            # "dataset": {
            #     # Fixed as the DATASET_NAME
            #     "name": DATASET_NAME,
            #     "subset": None,
            #     "split": "train"
            # },
            # "metrics": ["bleu"]
        

        with open(file_path, mode, encoding="utf8") as f:
            f.write("# Generated by utils.py\n")
            # Using sort_keys=False to maintain a readable order
            yaml.dump(config, f, sort_keys=False)
            
        # Print file name generated to confirm
        print(f"Generated: {file_name}")

    except FileExistsError:
        # Print a message to show file has been overwritten
        print(f"File: {file_name} (already exists). Using --overwrite to replace.")


def main() -> None:
    """Main function to parse arguments and generate all yaml files for the language pairs."""

    parser = argparse.ArgumentParser(
        description="Generate translation config YAML files for KenTrans language pairs."
    )
    # Allow overwriting
    parser.add_argument(
        "--overwrite",
        default=True,
        action="store_true",
        help="Overwrite files if they already exist",
    )
    # Changed default output dir to match the config generation 
    parser.add_argument(
        "--output-dir", default="./configs", help="Directory to write yaml files to"
    )

    args = parser.parse_args()

    # Ensure the output directory exists first 
    os.makedirs(args.output_dir, exist_ok=True)
    print(f"Output directory set to: {args.output_dir}")

    # Translation: Languages to 'swa' and back 
    target_lang_code = 'swa'
    
    # Create the lang-pairs: To swa and back, and not swa to swa
    required_pairs = set()
    for lang in available_langs:
        if lang != target_lang_code:
            required_pairs.add((lang, target_lang_code)) # Lang X -> swa
            required_pairs.add((target_lang_code, lang)) # swa -> Lang X

    # Check for all pairs to be translated 
    print(f"Generating configs for {len(required_pairs)} language pairs involving {target_lang_code}...")

    # Iterate over the derived set of required pairs
    for src, tgt in required_pairs:
        generate_yamls(
            output_dir=args.output_dir,
            overwrite=args.overwrite,
            src=src, 
            tgt=tgt  
        )

    print("\nConfiguration file generation complete.")


if __name__ == "__main__":
    main()
